# --- compare_dists.py:73 -- PAX records are content ---------------------------


def _sdist(path: Path, pax: dict[str, str]) -> None:
    with tarfile.open(path, mode="w:gz", format=tarfile.PAX_FORMAT) as archive:
        data = b"print('hi')\n"
        info = tarfile.TarInfo("pkg-1.0/pkg.py")
        info.size = len(data)
        info.pax_headers = pax
        archive.addfile(info, io.BytesIO(data))


def _compare(tmp_path: Path, first: dict[str, str], second: dict[str, str]) -> list[str]:
    a, b = tmp_path / "a", tmp_path / "b"
    a.mkdir()
    b.mkdir()
    _sdist(a / "pkg-1.0.tar.gz", first)
    _sdist(b / "pkg-1.0.tar.gz", second)
    errors, _report = compare_dists.compare(a, b)
    return errors


def test_sdists_differing_in_a_pax_record_are_not_content_identical(tmp_path: Path) -> None:
    errors = _compare(
        tmp_path, {"SCHILY.xattr.user.origin": "build-a"}, {"SCHILY.xattr.user.origin": "build-b"}
    )
    assert any("sdist content differs" in e for e in errors), errors


def test_sdists_differing_only_in_volatile_pax_records_agree(tmp_path: Path) -> None:
    errors = _compare(
        tmp_path,
        {"mtime": "1.5", "uname": "runner", "uid": "1001"},
        {"mtime": "2.5", "uname": "builder", "uid": "0"},
    )
    assert errors == []


# --- pypi.yml:66 -- the second build starts from a clean tree ------------------


def test_second_release_build_runs_in_a_fresh_worktree() -> None:
    workflow = gate.load_workflow_yaml(
        (REPO / ".github" / "workflows" / "pypi.yml").read_text(encoding="utf-8")
    )
    steps = workflow["jobs"]["build"]["steps"]
    title = "Build sdist + wheel twice and verify reproducibility"
    (step,) = [s for s in steps if "name" in s and s["name"].value == title]
    lines = [line.strip() for line in step["run"].value.splitlines()]
    assert 'git worktree add --detach "$RUNNER_TEMP/rebuild-src" HEAD' in lines
    assert (
        '(cd "$RUNNER_TEMP/rebuild-src" && python -m build --no-isolation '
        '--outdir "$RUNNER_TEMP/rebuild")'
    ) in lines
    assert lines.index("python -m build --no-isolation --outdir dist") < lines.index(
        'git worktree add --detach "$RUNNER_TEMP/rebuild-src" HEAD'
    )
    assert not any(line.startswith("rm -rf") for line in lines)


# --- the strict YAML subset reader --------------------------------------------

#: Decoded values produced by PyYAML 6.0.3 ``yaml.load(text, Loader=BaseLoader)``
#: (re-derived live below where PyYAML is installed).
GOLDEN: dict[str, object] = {
    "on: [push, 'pull_request']\npermissions: {}\n": {
        "on": ["push", "pull_request"],
        "permissions": {},
    },
    "a: >-\n  python -m pip\n  install build\n\n  x\n    more\n  y\n": {
        "a": "python -m pip install build\nx\n  more\ny"
    },
    "a: |\n  one\n\n  two\nb: 'it''s'\nc: \"t\\tu\\u00e9\"\n": {
        "a": "one\n\ntwo\n",
        "b": "it's",
        "c": "t\tu\u00e9",
    },
    "s:\n- x\n- k: v\n  m: [1, \"2\"]\n": {"s": ["x", {"k": "v", "m": ["1", "2"]}]},
    "a: >\n  last\n": {"a": "last\n"},
    "a: |\n  no final break": {"a": "no final break"},
    "k: v  # comment\nl: ${{ x == 'a' }}\n": {"k": "v", "l": "${{ x == 'a' }}"},
}


@pytest.mark.parametrize("text", list(GOLDEN))
def test_reader_matches_pyyaml_golden(text: str) -> None:
    assert gate.yaml_plain(gate.load_workflow_yaml(text)) == GOLDEN[text]


@pytest.mark.parametrize(
    "text",
    [
        "a: &x 1\nb: *x\n",
        "a: !!str 1\n",
        "a: one\n  two\n",
        "a: 'one\n  two'\n",
        "a: 1\na: 2\n",
        "a:\n\t- x\n",
        "a: x\tb\n",
        "a: |2\n  x\n",
        "a: |+\n  x\n",
        "---\na: 1\n",
        "%YAML 1.1\n---\na: 1\n",
        "a: [x,\n  y]\n",
        "a: [:\"main\"]\n",
        "a: b: c\n",
        "? a\n: b\n",
        "<<: {a: 1}\n",
        "a: |\n    x\n   y\n  z\n",
    ],
)
def test_reader_refuses_constructs_outside_the_subset(text: str) -> None:
    with pytest.raises(gate.WorkflowYamlError):
        gate.load_workflow_yaml(text)


def test_reader_matches_pyyaml_live() -> None:
    yaml = pytest.importorskip("yaml")
    texts = list(GOLDEN) + [
        path.read_text(encoding="utf-8")
        for path in sorted((REPO / ".github" / "workflows").glob("*.yml"))
    ]
    for text in texts:
        assert gate.yaml_plain(gate.load_workflow_yaml(text)) == yaml.load(
            text, Loader=yaml.BaseLoader
        ), text[:80]
