def _workflow(run_block: str) -> str:
    return (
        "name: Publish\non: workflow_dispatch\npermissions: {}\njobs:\n  build:\n"
        "    runs-on: ubuntu-latest\n    steps:\n"
        "      - run: |\n"
        "          python -m pip install --require-hashes -r .github/requirements/release.txt\n"
        f"{run_block}"
    )


def _reasons(text: str) -> list[str]:
    installs, unreadable = gate.find_pip_installs(text)
    return [r for r in (gate.classify(i) for i in installs) if r] + unreadable


# --- check_release_pins.py:197 -- a folded block is ONE shell command --------


def test_folded_run_block_is_read_as_one_command() -> None:
    folded = _workflow("      - run: >-\n          python -m pip\n          install build\n")
    assert any("not hash-pinned" in r for r in _reasons(folded)), _reasons(folded)


def test_literal_run_block_keeps_two_commands() -> None:
    """Positive control: in a LITERAL block the same two lines are two commands."""
    literal = _workflow("      - run: |\n          python -m pip\n          install build\n")
    assert _reasons(literal) == []


def test_pip_and_install_without_a_recognised_invocation_fail_closed() -> None:
    wrapped = _workflow('      - run: bash -c "pip install build"\n')
    assert any("no recognised pip invocation" in r for r in _reasons(wrapped)), _reasons(wrapped)


@pytest.mark.parametrize(
    "command",
    ["$PIP install build", "pip $CMD build", "python -m $MODULE install build"],
)
def test_installs_through_a_shell_expansion_fail_closed(command: str) -> None:
    """Found by running the gate's own fault class against it: the command or
    pip's sub-command decided at run time was invisible (no literal
    ``pip``+``install`` pair on the line)."""
    text = _workflow(f"          {command}\n")
    assert any("expansion" in r for r in _reasons(text)), _reasons(text)


def test_pip_commands_that_do_not_install_stay_clean() -> None:
    """Positive control for the nets above."""
    text = _workflow("          python -m pip check && pip --version && echo $HOME\n")
    assert _reasons(text) == []


def test_workflow_outside_the_yaml_subset_fails_closed() -> None:
    anchored = _workflow("      - run: &cmd pip install build\n")
    installs, unreadable = gate.find_pip_installs(anchored)
    assert installs == []
    assert any("cannot read the workflow as YAML" in r for r in unreadable), unreadable


