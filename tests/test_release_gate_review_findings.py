# --- check_release_pins.py:373 -- lock markers are evaluated ------------------


def _lock(entry: str) -> str:
    return f"{LOCK_HEADER}{entry} \\\n    --hash=sha256:{HASH}\n    # via -r release.in\n"


def test_lock_entry_excluded_by_its_marker_is_not_a_pin() -> None:
    lock, errors = gate.parse_lock(_lock('setuptools==84.0.0 ; python_version < "3"'))
    assert "setuptools" not in lock.pins
    assert not any("setuptools" in e for e in errors), errors


def test_lock_entry_included_by_its_marker_is_a_pin() -> None:
    lock, errors = gate.parse_lock(_lock('setuptools==84.0.0 ; python_version >= "3.11"'))
    assert lock.pins == {"setuptools": "84.0.0"}
    assert errors == []


@pytest.mark.parametrize(
    "marker",
    [
        'sys_platform == "linux"',
        'python_version ~= "3.12"',
        'python_version >= "3.*"',
        'python_version in "3.12"',
        'python_version >= "3.11" and',
    ],
)
def test_lock_marker_the_gate_cannot_evaluate_fails_closed(marker: str) -> None:
    lock, errors = gate.parse_lock(_lock(f"setuptools==84.0.0 ; {marker}"))
    assert "setuptools" not in lock.pins
    assert any("cannot evaluate environment marker" in e for e in errors), errors


@pytest.mark.parametrize(
    ("marker", "expected"),
    [
        ('python_version < "3.11"', False),
        ('python_version >= "3.12"', True),
        ('"3.13" > python_version', True),
        ('python_version == "3.12.0"', True),
        ('python_version < "3.11" or python_version >= "3.12"', True),
        ('(python_version >= "3.8" and python_version < "3.12")', False),
    ],
)
def test_marker_evaluation(marker: str, expected: bool) -> None:
    assert gate.evaluate_marker(marker, "3.12") is expected


